export function stripSrtFormatting(text: string): string {
  if (!text) return '';
  let cleaned = text;

  // 1. Remove markdown code blocks
  cleaned = cleaned.replace(/```(?:srt|text)?/gi, '');
  cleaned = cleaned.replace(/```/g, '');

  // 2. Remove page markers
  cleaned = cleaned.replace(/={2,}\s*ទំព័រទី[^\n=]*={2,}/gi, '');
  cleaned = cleaned.replace(/={2,}\s*Page[^\n=]*={2,}/gi, '');
  cleaned = cleaned.replace(/\[ទំព័រទី\s*[\d០-៩]+[^\]]*\]/gi, '');

  // 3. Remove partial tags at the end of streaming buffer
  cleaned = cleaned.replace(/\[(?:SRT_[0-9០-៩]*|អេសអាធី_[0-9០-៩]*|P[0-9០-៩]*|ភី[0-9០-៩]*)[^\]]*$/gi, '');

  // 4. Remove complete SRT tags: [SRT_1 | 00:00:01,000 --> 00:00:04,000] or [SRT_1]
  cleaned = cleaned.replace(/\[\s*(?:SRT|អេសអាធី)[\s_]*[0-9០-៩]+(?:\s*\|[^\n\]]*)?\]:?/gi, '');
  cleaned = cleaned.replace(/\[\s*(?:P|ភី)[0-9០-៩]+\s*\]:?/gi, '');
  cleaned = cleaned.replace(/\[កថាខណ្ឌ(?:ទី)?\s*[0-9០-៩]+\]:?/gi, '');

  // 5. Remove standard SRT blocks: index number + timecode line
  cleaned = cleaned.replace(
    /(?:^|\n)\s*[0-9០-៩]+\s*\n\s*[0-9០-៩]{1,2}:[0-9០-៩]{2}:[0-9០-៩]{2}[,\.][0-9០-៩]{2,3}\s*-->\s*[0-9០-៩]{1,2}:[0-9០-៩]{2}:[0-9០-៩]{2}[,\.][0-9០-៩]{2,3}[^\n]*/g,
    '\n'
  );

  // 6. Remove standalone timecode lines
  cleaned = cleaned.replace(
    /[0-9០-៩]{1,2}:[0-9០-៩]{2}:[0-9០-៩]{2}[,\.][0-9០-៩]{2,3}\s*-->\s*[0-9០-៩]{1,2}:[0-9០-៩]{2}:[0-9០-៩]{2}[,\.][0-9០-៩]{2,3}[^\n]*/g,
    ''
  );

  // 7. Remove standalone numbers that were cue indices on their own line
  cleaned = cleaned.replace(/(?:^|\n)\s*[0-9០-៩]+\s*(?=\n|$)/g, '\n');

  return cleaned;
}

export function cleanKhmerPunctuation(text: string): string {
  if (!text) return '';

  // First strip SRT formatting, tags, timecodes, and page markers
  let cleaned = stripSrtFormatting(text);

  // 2. Convert all Arabic numbers to 100% pure Khmer numbers
  cleaned = toKhmerNumerals(cleaned);

  // 3. Fix Khmer extra vowels (លើសស្រៈ), leaked Thai words, and Chuon Nath spelling
  cleaned = fixExtraVowelsAndWeirdKhmerClusters(cleaned).text;

  // 4. Remove markdown asterisks, hashes, backticks
  cleaned = cleaned.replace(/[\*\_`#~]/g, '');

  // 5. Remove quotation marks: "", '', “”, ‘’, «», 「」
  cleaned = cleaned.replace(/["'“”‘’«»「」]/g, ' ');

  // 6. Remove brackets and braces: (), [], {}, <>
  cleaned = cleaned.replace(/[()[\]{}<>]/g, ' ');

  // 7. Remove dashes, hyphens, colons, semicolons: —, –, -, :, ;
  cleaned = cleaned.replace(/[—–\-:;]/g, ' ');

  // 8. Convert exclamation marks '!' or standard periods '.' to Khmer khan '។'
  cleaned = cleaned.replace(/!+/g, '។');
  cleaned = cleaned.replace(/\.+/g, '។');

  // 9. Normalize multiple spaces into single space
  cleaned = cleaned.replace(/[ \t]+/g, ' ');

  // 10. Normalize multiple consecutive '។' (e.g. ។។, ។ ។) to single '។'
  cleaned = cleaned.replace(/[។\s]*។[។\s]*/g, '។ ');

  // 11. Normalize multiple consecutive '?' to single '?'
  cleaned = cleaned.replace(/[?\s]*\?[?\s]*/g, '? ');

  // 12. Clean line breaks
  cleaned = cleaned
    .split('\n')
    .map((line) => line.trim())
    .join('\n')
    .replace(/\n{3,}/g, '\n\n');

  return cleaned.trim();
}

/**
 * Formats translation as continuous, cohesive reading text where dialogue and sentences
 * flow connected together as a smooth, readable story.
 */
export function formatAsContinuousStoryText(text: string): string {
  if (!text) return '';

  const cleaned = cleanKhmerPunctuation(text);
  if (!cleaned) return '';

  const rawLines = cleaned
    .split('\n')
    .map((l) => l.trim())
    .filter((l) => l.length > 0);

  if (rawLines.length === 0) return '';

  const paragraphs: string[] = [];
  let currentPara = '';
  let sentenceCount = 0;

  for (const line of rawLines) {
    if (!currentPara) {
      currentPara = line;
    } else {
      const endsWithKhmerPunct = currentPara.endsWith('។') || currentPara.endsWith('?');
      if (endsWithKhmerPunct) {
        currentPara += ' ' + line;
        sentenceCount++;
      } else {
        currentPara += ' ' + line;
      }
    }

    const endsWithPunct = currentPara.endsWith('។') || currentPara.endsWith('?');
    if (endsWithPunct && (sentenceCount >= 3 || currentPara.length >= 320)) {
      paragraphs.push(currentPara);
      currentPara = '';
      sentenceCount = 0;
    }
  }

  if (currentPara) {
    paragraphs.push(currentPara);
  }

  return paragraphs.join('\n\n');
}

/**
 * Extracts active paragraph index from raw streaming text that contains [P1], [P2], etc.
 */
export function extractActiveParagraphIndex(rawStreamText: string): number {
  if (!rawStreamText) return 0;
  const matches = [...rawStreamText.matchAll(/\[(?:P|ភី)([0-9០-៩]+)\]/gi)];
  if (matches.length > 0) {
    const lastMatch = matches[matches.length - 1];
    const asciiDigits = lastMatch[1].replace(/[០-៩]/g, (d) => KHMER_TO_ARABIC_DIGITS[d] ?? d);
    const pNum = parseInt(asciiDigits, 10);
    return Math.max(0, pNum - 1);
  }
  return 0;
}

/**
 * Extracts active SRT cue id from raw streaming text that contains [SRT_X ...].
 */
export function extractActiveSrtCueId(rawStreamText: string): number | null {
  if (!rawStreamText) return null;
  const matches = [...rawStreamText.matchAll(/\[(?:SRT|អេសអាធី)[\s_]*([0-9០-៩]+)/gi)];
  if (matches.length > 0) {
    const lastMatch = matches[matches.length - 1];
    const asciiDigits = lastMatch[1].replace(/[០-៩]/g, (d) => KHMER_TO_ARABIC_DIGITS[d] ?? d);
    const cueId = parseInt(asciiDigits, 10);
    return isNaN(cueId) ? null : cueId;
  }
  const srtMatches = [
    ...rawStreamText.matchAll(/(?:^|\n)\s*([0-9០-៩]+)\s*\n\s*[0-9០-៩]{1,2}:[0-9០-៩]{2}:[0-9០-៩]{2}/g),
  ];
  if (srtMatches.length > 0) {
    const lastMatch = srtMatches[srtMatches.length - 1];
    const asciiDigits = lastMatch[1].replace(/[០-៩]/g, (d) => KHMER_TO_ARABIC_DIGITS[d] ?? d);
    const cueId = parseInt(asciiDigits, 10);
    return isNaN(cueId) ? null : cueId;
  }
  return null;
}

/**
 * Filters out any bogus/legacy '(លុបចោល)' or empty replacement entries from a CorrectionDiffItem array.
 */
export function sanitizeCorrectionItems(
  items?: CorrectionDiffItem[]
): CorrectionDiffItem[] {
  if (!Array.isArray(items) || items.length === 0) return [];
  const collector = new CorrectionCollector();
  for (const item of items) {
    if (!item || !item.wrongText || !item.fixedText) continue;
    const w = item.wrongText.trim();
    const f = item.fixedText.trim();
    if (!w || !f || f === '(លុបចោល)' || w === '(លុបចោល)' || w === f) continue;
    collector.add(w, f, item.category, item.count || 1);
  }
  return collector.values();
}

/**
 * Computes a complete list of all wrong words/phrases (អក្សរដែលខុស) and their corrected
 * Khmer replacements (អក្សរដែលកែរួច) between beforeText and afterText.
 * Strictly records ONLY genuine word/phrase repairs and NEVER outputs '(លុបចោល)'.
 */
export function computeKhmerCorrectionDiffs(
  beforeText: string,
  afterText: string
): CorrectionDiffItem[] {
  if (!beforeText) return [];

  // 1. Collect all exact repairs directly from our deterministic repair pass on beforeText
  const directPass = fixKhmerSpellingAndForeignText(beforeText, {
    removeOrTransliterateAllForeign: true,
    preserveTags: true,
  });

  const collector = new CorrectionCollector();
  for (const item of directPass.corrections) {
    collector.add(item.wrongText, item.fixedText, item.category, item.count);
  }

  if (!afterText || beforeText === afterText) {
    return collector.values();
  }

  // 2. Also check if any specific anomalous token in beforeText (containing foreign script or stacked vowels)
  // was replaced with a different Khmer word in afterText (e.g. by AI context repair)
  const sanitizeLine = (s: string) =>
    s
      .replace(/\[(?:SRT_\d+(?:\s*\|[^\n\]]*)?|P\d+)\]:?/gi, ' ')
      .replace(/[។?.,!()[\]{}"'«»—–\-]+/g, ' ')
      .trim();

  const bLines = beforeText.split(/\n+/).map(sanitizeLine).filter(Boolean);
  const aLines = afterText.split(/\n+/).map(sanitizeLine).filter(Boolean);

  // Only do token alignment when line counts match so misaligned paragraphs never cause false diffs
  if (bLines.length === aLines.length) {
    for (let idx = 0; idx < bLines.length; idx++) {
      const bTokens = bLines[idx].split(/\s+/).filter(Boolean);
      const aTokens = aLines[idx].split(/\s+/).filter(Boolean);
      if (bTokens.length === aTokens.length) {
        for (let t = 0; t < bTokens.length; t++) {
          const w = bTokens[t];
          const f = aTokens[t];
          if (w !== f && w.length <= 45 && f.length <= 45 && f.length > 0) {
            collector.add(w, f);
          }
        }
      }
    }
  }

  return collector.values();
}


