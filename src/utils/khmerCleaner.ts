export interface CorrectionDiffItem {
  id: string;
  wrongText: string;
  fixedText: string;
  category: 'ច្រឡំភាសា / អក្សរចម្លែក' | 'លើសស្រៈ' | 'អក្ខរាវិរុទ្ធ / បំពេញពាក្យដាច់' | 'បម្លែងលេខ';
  count: number;
}

export function classifyCorrectionCategory(
  wrongText: string
): CorrectionDiffItem['category'] {
  if (/(?![\u1780-\u17FF\u19E0-\u19FF])[\p{L}\p{M}]|[\u25CC\uFFFD]/u.test(wrongText)) {
    return 'ច្រឡំភាសា / អក្សរចម្លែក';
  }
  if (/[\u17B6-\u17C5]{2,}|([\u17C6-\u17D1])\1+/.test(wrongText)) {
    return 'លើសស្រៈ';
  }
  if (/[0-9០-៩]/.test(wrongText)) {
    return 'បម្លែងលេខ';
  }
  return 'អក្ខរាវិរុទ្ធ / បំពេញពាក្យដាច់';
}

export class CorrectionCollector {
  private map = new Map<string, CorrectionDiffItem>();

  add(
    wrongRaw: string,
    fixedRaw: string,
    category?: CorrectionDiffItem['category'],
    incrementBy = 1
  ) {
    const w = (wrongRaw || '').trim();
    const f = (fixedRaw || '').trim();
    // STRICT RULE: Never record empty replacements, "(លុបចោល)", or identical strings
    if (!w || !f || w === f || f === '(លុបចោល)' || w === '(លុបចោល)') return;
    if (!/[\p{L}\p{M}0-9០-៩]/u.test(w)) return;
    // Ignore invisible-only canonicalization where rendered visual string is essentially unchanged
    const normalizeVisual = (str: string) =>
      str
        .replace(/េា/g, 'ោ')
        .replace(/េី/g, 'ើ')
        .replace(/[\u200B-\u200F\uFEFF]/g, '')
        .trim();
    if (normalizeVisual(w) === normalizeVisual(f)) return;

    const key = `${w}___${f}`;
    const existing = this.map.get(key);
    if (existing) {
      existing.count += incrementBy;
    } else {
      this.map.set(key, {
        id: `diff_${this.map.size + 1}`,
        wrongText: w,
        fixedText: f,
        category: category || classifyCorrectionCategory(w),
        count: incrementBy,
      });
    }
  }

  values(): CorrectionDiffItem[] {
    return Array.from(this.map.values());
  }
}

/**
 * Fixes Khmer extra/stacked vowels (លើសស្រៈ), broken consonant clusters,
 * and weird/garbled characters (អក្សរចម្លែកៗ).
 */
export function fixExtraVowelsAndWeirdKhmerClusters(
  text: string,
  collector?: CorrectionCollector
): {
  text: string;
  fixesCount: number;
} {
  if (!text) return { text: '', fixesCount: 0 };

  let fixesCount = 0;
  let s = text;

  // 1. Remove zero-width characters, replacement chars (\uFFFD), dotted circles (\u25CC), private-use/control glitches, citation tags, and parentheses
  s = s.replace(/[\u200B-\u200F\u202A-\u202E\u2060-\u206F\uFEFF\uFFFD\u25CC]/g, () => {
    fixesCount++;
    return '';
  });
  // Strip any system citation tags ([cite:...], [source], 【...】) and parentheses ( )
  s = s.replace(/\[\s*(?:cite|source)[^\]]*\]|【[^】]*】/gi, () => {
    fixesCount++;
    return '';
  });
  s = s.replace(/[()（）]/g, () => {
    fixesCount++;
    return ' ';
  });

  // 2. Translate common leaked Thai words/phrases & mixed-script glued syllables (e.g. គ្នាอย่างรุนแรง, διοាក់គំនិតនោះ, তরwសាង, ដ៏ကြမ်းដុះដំបូ)
  for (const [thaiRegex, khmerPhrase] of THAI_LEAK_TO_KHMER_DICTIONARY) {
    s = s.replace(thaiRegex, (match) => {
      const replaced = match.replace(thaiRegex, khmerPhrase);
      if (match !== replaced) {
        fixesCount++;
        collector?.add(match, replaced, 'ច្រឡំភាសា / អក្សរចម្លែក');
      }
      return replaced;
    });
  }

  // 2b. If any non-Khmer letters are glued directly before a Khmer dependent vowel/sign (e.g., [foreign]+ាក់, [foreign]+ាន, [foreign]+ាំង),
  // restore the missing Khmer base consonant so the vowel is never orphaned or deleted!
  s = s.replace(
    /([\u1780-\u17FF]*)(?:(?![\u1780-\u17FF\u19E0-\u19FF])[\p{L}\p{M}])+([\u17B6-\u17D1][\u1780-\u17FF]*)/gu,
    (fullMatch, khmerPrefix: string, khmerRemainder: string) => {
      fixesCount++;
      let baseConsonant = 'អ';
      if (khmerRemainder.startsWith('ាក់')) baseConsonant = 'ដ';
      else if (khmerRemainder.startsWith('ាន')) baseConsonant = 'ប';
      else if (khmerRemainder.startsWith('ាំង')) baseConsonant = 'ទ';
      else if (khmerRemainder.startsWith('ើង')) baseConsonant = 'ឡ';
      else if (khmerRemainder.startsWith('ួយ')) baseConsonant = 'ជ';
      else if (khmerRemainder.startsWith('ុំវិញ')) baseConsonant = 'ជ';
      const fixedToken = `${khmerPrefix || ''}${baseConsonant}${khmerRemainder}`;
      collector?.add(fullMatch, fixedToken, 'ច្រឡំភាសា / អក្សរចម្លែក');
      return fixedToken;
    }
  );

  // 2c. Guarantee 0% Thai (\u0E00-\u0E7F) or Lao (\u0E80-\u0EFF) characters remain glued inside or adjacent to Khmer words
  if (/[\u0E00-\u0EFF]/.test(s)) {
    s = s.replace(
      /([\u1780-\u17FF]*)[\u0E00-\u0EFF]+([\u1780-\u17FF]*)/g,
      (fullMatch, prefix: string, suffix: string) => {
        fixesCount++;
        const combinedKhmer = `${prefix || ''}${suffix || ''}`;
        if (combinedKhmer.length > 0) {
          collector?.add(fullMatch, combinedKhmer, 'ច្រឡំភាសា / អក្សរចម្លែក');
          return combinedKhmer;
        }
        return '';
      }
    );
  }

  // 3. Normalize split composite Khmer vowels into single canonical Unicode codepoints
  const compositeReplacements: Array<[RegExp, string]> = [
    [/េា/g, 'ោ'], // e + a -> ao
    [/ាេ/g, 'ោ'], // reversed a + e -> ao
    [/េី/g, 'ើ'], // e + ii -> oe
    [/ីេ/g, 'ើ'], // reversed ii + e -> oe
    [/េើ/g, 'ើ'], // e + oe -> oe
    [/ើេ/g, 'ើ'], // reversed oe + e -> oe
    [/េឿ/g, 'ឿ'],
    [/ឿេ/g, 'ឿ'],
    [/េៀ/g, 'ៀ'],
    [/ៀេ/g, 'ៀ'],
    [/ំុ/g, 'ុំ'], // nikahit before u -> u + nikahit
    [/ំា/g, 'ាំ'], // nikahit before aa -> aa + nikahit
    [/ះេ/g, 'េះ'],
    [/ះោ/g, 'ោះ'],
    [/ះុ/g, 'ុះ'],
    [/ះិ/g, 'ិះ'],
    [/ះឹ/g, 'ឹះ'],
    // Shifter (ត្រីសព្ទ ៊ / មូសិកទន្ត ៉) placed after dependent vowel -> move before dependent vowel
    [/([\u17B6-\u17C5])([\u17C9\u17CA])/g, '$2$1'],
  ];

  for (const [pattern, replacement] of compositeReplacements) {
    s = s.replace(pattern, (m) => {
      fixesCount++;
      if (replacement.includes('$')) {
        return m.replace(pattern, replacement);
      }
      return replacement;
    });
  }

  // 4. Fix stacked / extra dependent vowels (លើសស្រៈ) and duplicate signs inside Khmer clusters while recording the exact word before/after
  s = s.replace(/[\u1780-\u17FF]+/g, (khmerCluster) => {
    let fixedCluster = khmerCluster;
    // Repair corrupted shifter + អ + dependent vowel sequences (e.g. ស៊អី -> ស៊ី, រ៊អី -> រ៊ី)
    fixedCluster = fixedCluster.replace(
      /([\u1780-\u17A2](?:\u17D2[\u1780-\u17A2])?[\u17C9\u17CA])អ([\u17B6-\u17C5])/g,
      '$1$2'
    );
    // Remove duplicate coeng signs (្្ -> ្) or trailing coeng
    fixedCluster = fixedCluster.replace(/\u17D2{2,}/g, '\u17D2').replace(/\u17D2$/g, '');
    // Remove duplicate shifters or signs (៉៉, ៊៊, ់់, ៍៍, ៎៎, ៏៏, ័័, ំំ, ះះ)
    fixedCluster = fixedCluster.replace(/([\u17C6-\u17D1])\1+/g, '$1');
    // Fix stacked dependent vowels (លើសស្រៈ) on the same consonant
    fixedCluster = fixedCluster.replace(/([\u17B6-\u17C5])[\u17B6-\u17C5]+/g, '$1');
    // Fix dependent vowel + shifter + another dependent vowel on the same consonant (e.g. កា៉ា -> ក៉ា)
    fixedCluster = fixedCluster.replace(
      /([\u17B6-\u17C5])([\u17C9\u17CA])[\u17B6-\u17C5]+/g,
      '$2$1'
    );
    // Fix duplicate nikahit/reahmuk/bantoc combinations
    fixedCluster = fixedCluster.replace(/([\u17C6\u17C7\u17CB])[\u17C6\u17C7\u17CB]+/g, '$1');

    if (fixedCluster !== khmerCluster) {
      fixesCount++;
      if (fixedCluster.length > 0) {
        collector?.add(khmerCluster, fixedCluster, 'លើសស្រៈ');
      }
    }
    return fixedCluster;
  });

  // 5. Remove orphan dependent vowels, signs, or coeng at the start of a line or after whitespace/punctuation
  s = s.replace(/(^|[ \t\n។?.,!()[\]{}"'«»—–\-])[\u17B6-\u17D2]+/g, (_, prefix) => {
    fixesCount++;
    return prefix;
  });

  // 5b. Strip scraped Cambodian news headline hallucinations, NMT speech tail hallucinations & website footers first (both spaced and unspaced)
  s = s.replace(
    /\s*នាយក\s*វិទ្យាល័យ\s*លី\s*យ៉ុង\s*ផាត់(?:\s*រៀបចំ\s*ការ\s*ប្រកួត)?(?:\s*ដ[ណំ]\u17D2[តដ]ើម\s*ខ្សែ\s*ក្រវាត់\s*ស្រា\s*បៀរ\s*អាន់\s*ឆ័\s*រ)?(?:\s*\|?\s*(?:កាមបូដីអា\s*នេវស|Cambodia\s*News)?\s*\|?\s*(?:ខមឺ\s*នេវស|Khmer\s*News)?\s*(?:ព[ត័]៌មាន\s*ខ្មែរ)?)*/gi,
    ''
  );
  s = s.replace(
    /\s*ដ[ណំ]\u17D2[តដ]ើម\s*ខ្សែ\s*ក្រវាត់\s*ស្រា\s*បៀរ\s*អាន់\s*ឆ័\s*រ/gi,
    ''
  );
  s = s.replace(
    /\s*\|?\s*(?:កាមបូដីអា\s*នេវស|Cambodia\s*News)\s*\|?\s*(?:ខមឺ\s*នេវស|Khmer\s*News)?\s*(?:ព[ត័]៌មាន\s*ខ្មែរ)?/gi,
    ''
  );
  s = s.replace(/\s*នាយក\s*វិទ្យាល័យ\s*$/g, '');
  s = s.replace(
    /\s*(?:ប៉ុន្តែ)?\s*ខ្ញុំ\s*សូម\s*ជម្រាប\s*ជូន\s*ឯកឧត្តម\s*លោកជំទាវ(?:\s*ខ្ញុំ\s*នឹង\s*ជម្រាប\s*ជូន\s*ឯកឧត្តម\s*លោកជំទាវ)*/g,
    ''
  );

  // 6. Join split Khmer compound words and de-tokenize word-spaced SMT/NMT sentences (e.g., "អ្នក នឹង បាត់ បង់ ក្បាល របស់ អ្នក ទេ" -> "អ្នកនឹងមិនបាត់បង់ក្បាលរបស់អ្នកទេ")
  const splitCompoundPairs: Array<[RegExp, string]> = [
    [/ក្នុង\s*កលាសស\s*មួយ/g, 'ក្នុងថ្នាក់រៀនមួយ'],
    [/កលាសស/g, 'ថ្នាក់រៀន'],
    [/កលាបសស/g, 'ក្លឹប'],
    [/កលុបសស?/g, 'ក្លឹប'],
    [/កលាប(?=[ \t\n។?.,!]|មួយ|នេះ|នោះ|$)/g, 'ក្លឹប'],
    [/ក្នុង\s+ថ្នាក់រៀន\s+មួយ/g, 'ក្នុងថ្នាក់រៀនមួយ'],
    [/ក្នុង\s+ថ្នាក់\s+មួយ/g, 'ក្នុងថ្នាក់មួយ'],
    [/វីលលាហ្គេ\s*ឆីអេហ្វ/g, 'មេភូមិ'],
    [/វីលលាហ្គេ/g, 'ភូមិ'],
    [/ដីវរកេ/g, 'ការលែងលះ'],
    [/កូនកុបីនេ/g, 'ប្រពន្ធចុង'],
    [/លោកគ្រូ\s*សុ\s*វ័យក្មេង/g, 'អ្នកប្រុសតូច ស៊ូ'],
    [/លោកគ្រូ\s*ស៊ូ\s*វ័យក្មេង/g, 'អ្នកប្រុសតូច ស៊ូ'],
    [/អាណិតណាស់លោកគ្រូ\s*ស៊ូ/g, 'សូមអភ័យទោសអ្នកប្រុសតូច ស៊ូ'],
    [/អាណិតលោកគ្រូ\s*ស៊ូ\s*ណាស់/g, 'សូមអភ័យទោសអ្នកប្រុសតូច ស៊ូ'],
    [/ជាំង\s*យិន/g, 'ជៀង អ៊ីន'],
    [/ព្យាបាលអ្នកឱ្យកាន់តែប្រសើរឡើង/g, 'មើលថែអ្នកឱ្យកាន់តែប្រសើរឡើង'],
    [/ដែលនឹងមិនធ្វើទាល់តែសោះ/g, 'រឿងនោះមិនអាចទៅរួចទាល់តែសោះ'],
    [/នោះនឹងមិនធ្វើនោះទេ/g, 'រឿងនោះមិនអាចធ្វើទៅរួចទេ'],
    [/ធំ\s*បងប្អូនប្រុស\s*សុ/g, 'បងប្រុសធំ ស៊ូ'],
    [/ធំ\s*បងប្អូនប្រុស\s*ស៊ូ/g, 'បងប្រុសធំ ស៊ូ'],
    [/ហួនសី\s*ផ្ទះ/g, 'ហាងហួនស៊ី'],
    [/ហួនស៊ី\s*ផ្ទះ/g, 'ហាងហួនស៊ី'],
    [/បាត់\s+បង់/g, 'បាត់បង់'],
    [/ព្រះ\s+មហាក្សត្រ/g, 'ព្រះមហាក្សត្រ'],
    [/អ្នក\s+រាល់\s+គ្នា/g, 'អ្នករាល់គ្នា'],
    [/ទាំង\s+អស់\s+គ្នា/g, 'ទាំងអស់គ្នា'],
    [/ទើប\s+តែ/g, 'ទើបតែ'],
    [/នៅ\s+ក្នុង/g, 'នៅក្នុង'],
    [/នៅ\s+លើ/g, 'នៅលើ'],
    [/នៅ\s+ក្រោម/g, 'នៅក្រោម'],
    [/នៅ\s+ឯ/g, 'នៅឯ'],
    [/ទាំង\s+អស់/g, 'ទាំងអស់'],
    [/ស្នាក់\s+នៅ/g, 'ស្នាក់នៅ'],
    [/ខាង\s+មុខ/g, 'ខាងមុខ'],
    [/ខាង\s+ក្រោយ/g, 'ខាងក្រោយ'],
    [/ខាង\s+ក្នុង/g, 'ខាងក្នុង'],
    [/ខាង\s+ក្រៅ/g, 'ខាងក្រៅ'],
    [/ដែរ\s+ឬ\s+ទេ/g, 'ដែរឬទេ'],
    [/មែន\s+ឬ\s+ទេ/g, 'មែនឬទេ'],
    [/ដោយ\s+សារ\s+តែ/g, 'ដោយសារតែ'],
    [/ដោយ\s+សារ/g, 'ដោយសារ'],
    [/មក\s+ដល់/g, 'មកដល់'],
    [/ទៅ\s+ដល់/g, 'ទៅដល់'],
    [/ទី\s+នេះ/g, 'ទីនេះ'],
    [/ទី\s+នោះ/g, 'ទីនោះ'],
    [/មើល\s+ទៅ/g, 'មើលទៅ'],
    [/ស្រស់\s+ស្អាត\s+ណាស់/g, 'ស្រស់ស្អាតណាស់'],
    [/ស្រស់\s+ស្អាត/g, 'ស្រស់ស្អាត'],
    [/ជា\s+ច្រើន/g, 'ជាច្រើន'],
    [/សម្រាប់\s+ការ/g, 'សម្រាប់ការ'],
    [/បន្ទប់\s+ឯកជន/g, 'បន្ទប់ឯកជន'],
    [/ការ\s+ប្រឡង/g, 'ការប្រឡង'],
    [/ការ\s+ប្រកួត/g, 'ការប្រកួត'],
    [/តើ\s+អ្នក\s+([\u1780-\u17FF]{1,10})\s+ទេ/g, 'តើអ្នក$1ទេ'],
    [/វា\s+ជា\s+([\u1780-\u17FF]{1,10})\s+មួយ/g, 'វាជា$1មួយ'],
  ];

  for (const [compRegex, compJoined] of splitCompoundPairs) {
    s = s.replace(compRegex, (m) => {
      const replaced = m.replace(compRegex, compJoined);
      if (replaced !== m) {
        fixesCount++;
        collector?.add(m, replaced, 'អក្ខរាវិរុទ្ធ / បំពេញពាក្យដាច់');
      }
      return replaced;
    });
  }

  // De-tokenize sequences of 5 or more short Khmer words separated by single spaces (word-by-word SMT spacing)
  s = s.replace(
    /[\u1780-\u17FF]{1,10}(?:[ \t]+[\u1780-\u17FF]{1,10}){4,}/g,
    (spacedRun) => {
      const tokens = spacedRun.trim().split(/[ \t]+/);
      // Only de-tokenize if average token length is short (<= 6.2 chars, typical of word-segmented Khmer)
      const avgLen =
        tokens.reduce((sum, tok) => sum + tok.length, 0) / Math.max(1, tokens.length);
      if (avgLen > 6.2) return spacedRun;

      const clauseBreakBefore = new Set([
        'ប៉ុន្តែ',
        'ដូច្នេះ',
        'ព្រោះ',
        'ពីព្រោះ',
        'ប្រសិនបើ',
        'ទោះបីជា',
        'បន្ទាប់មក',
        'កម្រិត',
      ]);

      let joined = tokens[0];
      for (let i = 1; i < tokens.length; i++) {
        const tok = tokens[i];
        const prev = tokens[i - 1];
        if (
          clauseBreakBefore.has(tok) ||
          prev === 'កម្រិត' ||
          (/^(?:បងប្រុស|បងស្រី|ប្អូនប្រុស|ប្អូនស្រី|អ្នកប្រុសតូច|អ្នកប្រុស|លោកគ្រូ|លោក|អ្នកនាង)$/.test(
            prev
          ) &&
            tok.length <= 5)
        ) {
          joined += ' ' + tok;
        } else {
          joined += tok;
        }
      }

      if (joined !== spacedRun) {
        fixesCount++;
        collector?.add(
          spacedRun.length > 60 ? spacedRun.slice(0, 57) + '...' : spacedRun,
          joined.length > 60 ? joined.slice(0, 57) + '...' : joined,
          'អក្ខរាវិរុទ្ធ / បំពេញពាក្យដាច់'
        );
      }
      return joined;
    }
  );

  // 7. Apply standard Chuon Nath spelling corrections and record exact word fixes
  for (const [pattern, replacement] of KHMER_SPELLING_CORRECTIONS) {
    s = s.replace(pattern, (match) => {
      const replaced = match.replace(pattern, replacement);
      if (match !== replaced) {
        fixesCount++;
        // Record substantial spelling/truncated word fixes (skip trivial ឲ -> ឱ្យ unless part of a word)
        if (
          replaced.trim().length > 0 &&
          match !== 'ឲ' &&
          match !== 'ឲ្យ' &&
          match !== 'អោយ'
        ) {
          collector?.add(match, replaced, 'អក្ខរាវិរុទ្ធ / បំពេញពាក្យដាច់');
        }
      }
      return replaced;
    });
  }

  // 8. Deduplicate consecutive identical sentences (e.g., stuttered NMT sentences repeated twice in a row)
  s = s.replace(/([\u1780-\u17FF][^។?\n]{8,120}[។?])\s*\1+/g, '$1');

  return { text: s, fixesCount };
}

/**
 * Converts a non-negative integer BigInt or number into spoken Khmer words
 * e.g. 0 -> សូន្យ, 25 -> ម្ភៃប្រាំ, 100 -> មួយរយ, 12500 -> មួយម៉ឺនពីរពាន់ប្រាំរយ
 */
export function integerToKhmerWords(numStr: string): string {
  const cleanDigits = numStr.replace(/^0+(?=\d)/, '');
  if (!cleanDigits || cleanDigits === '0') return 'សូន្យ';

  const ones = [
    '',
    'មួយ',
    'ពីរ',
    'បី',
    'បួន',
    'ប្រាំ',
    'ប្រាំមួយ',
    'ប្រាំពីរ',
    'ប្រាំបី',
    'ប្រាំបួន',
  ];
  const tens = [
    '',
    'ដប់',
    'ម្ភៃ',
    'សាមសិប',
    'សែសិប',
    'ហាសិប',
    'ហុកសិប',
    'ចិតសិប',
    'ប៉ែតសិប',
    'កៅសិប',
  ];

  // For extremely long digit strings (>15 digits), read digit-by-digit
  if (cleanDigits.length > 15) {
    return cleanDigits
      .split('')
      .map((d) => (d === '0' ? 'សូន្យ' : ones[parseInt(d, 10)] || ''))
      .join('');
  }

  const n = BigInt(cleanDigits);
  if (n === 0n) return 'សូន្យ';

  const convertBelowMillion = (val: number): string => {
    if (val === 0) return '';
    let rem = val;
    let out = '';

    if (rem >= 100000) {
      const saen = Math.floor(rem / 100000);
      out += ones[saen] + 'សែន';
      rem %= 100000;
    }
    if (rem >= 10000) {
      const muen = Math.floor(rem / 10000);
      out += ones[muen] + 'ម៉ឺន';
      rem %= 10000;
    }
    if (rem >= 1000) {
      const poan = Math.floor(rem / 1000);
      out += ones[poan] + 'ពាន់';
      rem %= 1000;
    }
    if (rem >= 100) {
      const roy = Math.floor(rem / 100);
      out += ones[roy] + 'រយ';
      rem %= 100;
    }
    if (rem >= 10) {
      const t = Math.floor(rem / 10);
      out += tens[t];
      rem %= 10;
    }
    if (rem > 0) {
      out += ones[rem];
    }
    return out;
  };

  let remaining = n;
  const million = 1000000n;
  const billion = 1000000000n;
  const trillion = 1000000000000n;

  let result = '';

  if (remaining >= trillion) {
    const trillions = Number(remaining / trillion);
    result += convertBelowMillion(trillions) + 'ទ្រីលាន';
    remaining %= trillion;
  }

  if (remaining >= billion) {
    const billions = Number(remaining / billion);
    result += convertBelowMillion(billions) + 'ពាន់លាន';
    remaining %= billion;
  }

  if (remaining >= million) {
    const millions = Number(remaining / million);
    result += convertBelowMillion(millions) + 'លាន';
    remaining %= million;
  }

  if (remaining > 0n) {
    result += convertBelowMillion(Number(remaining));
  }

  return result;
}

/**
 * Converts ALL numbers (both Khmer numerals ០-៩ and Arabic numerals 0-9, including
 * comma-separated numbers, decimals, and percentages) into pure Khmer words (អក្សរខ្មែរសុទ្ធ).
 * Preserves [P1] and [SRT_1 | ...] tags when preserveTags=true.
 */
export function convertAllNumbersToKhmerWords(
  text: string,
  options?: { preserveTags?: boolean }
): {
  text: string;
  convertedCount: number;
} {
  if (!text) return { text: '', convertedCount: 0 };

  const preserveTags = options?.preserveTags ?? true;
  const savedTags: string[] = [];
  let working = text;

  if (preserveTags) {
    working = working.replace(
      /\[(?:SRT_\d+(?:\s*\|[^\n\]]*)?|P\d+)\]:?/gi,
      (match) => {
        const idx = savedTags.length;
        savedTags.push(match);
        return `__KH_TAG_NUM_${idx}__`;
      }
    );
  }

  let convertedCount = 0;

  // Normalize any Khmer digit string to Arabic digits helper
  const toAsciiDigits = (str: string) =>
    str.replace(/[០-៩]/g, (d) => KHMER_TO_ARABIC_DIGITS[d] ?? d);

  // Match numbers (Arabic 0-9 or Khmer ០-៩) with optional comma separators, decimals, and trailing %
  // Make sure we don't match inside __KH_TAG_NUM_x__
  working = working.replace(
    /(__KH_TAG_NUM_\d+__)|([0-9០-៩]{1,3}(?:,[0-9០-៩]{3})+|[0-9០-៩]+)(?:\.([0-9០-៩]+))?(\s*%)?/g,
    (fullMatch, tagMatch, intPart, decPart, percentPart) => {
      if (tagMatch) return tagMatch;
      if (!intPart) return fullMatch;

      convertedCount++;
      const cleanInt = toAsciiDigits(intPart.replace(/,/g, ''));
      let words = integerToKhmerWords(cleanInt);

      if (decPart) {
        const cleanDec = toAsciiDigits(decPart);
        const decWords = cleanDec
          .split('')
          .map((d) => integerToKhmerWords(d))
          .join('');
        words += 'ចុច' + decWords;
      }

      if (percentPart) {
        words += 'ភាគរយ';
      }

      return words;
    }
  );

  if (preserveTags && savedTags.length > 0) {
    working = working.replace(/__KH_TAG_NUM_(\d+)__/g, (_, idxStr) => {
      const idx = parseInt(idxStr, 10);
      return savedTags[idx] ?? '';
    });
  }

  return { text: working, convertedCount };
}

